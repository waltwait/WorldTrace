export function findAirport(iata: string): AirportInfo | null {
  if (!iata) return null;
  const upper = iata.trim().toUpperCase();
  return AIRPORTS_DB[upper] ?? null;
}

export function getUtcOffsetHours(tz: string, refDate: Date = new Date()): number | null {
  try {
    const formatter = new Intl.DateTimeFormat('en-US', {
      timeZone: tz,
      year: 'numeric',
      month: 'numeric',
      day: 'numeric',
      hour: 'numeric',
      minute: 'numeric',
      second: 'numeric',
      hour12: false,
    });
    const parts = formatter.formatToParts(refDate);
    const p: Record<string, string> = {};
    for (const part of parts) {
      p[part.type] = part.value;
    }
    const year = Number(p.year);
    const month = Number(p.month) - 1;
    const day = Number(p.day);
    let hour = Number(p.hour);
    if (hour === 24) hour = 0;
    const minute = Number(p.minute);
    const second = Number(p.second);

    const asUtc = Date.UTC(year, month, day, hour, minute, second);
    return Math.round((asUtc - refDate.getTime()) / (1000 * 60 * 60));
  } catch {
    return null;
  }
}

export function getArrivalTimezoneSummary(
  depIata: string,
  arrIata: string,
  refDate: Date = new Date(),
): TimezoneSummary {
  const dep = findAirport(depIata);
  const arr = findAirport(arrIata);

  if (!dep || !arr) {
    return {
      hasDifference: false,
      hourDifference: 0,
      headline: 'Timezone info unavailable',
      description: 'Airport timezone information is not in the database.',
      badge: 'UTC',
    };
  }

  const depOffset = getUtcOffsetHours(dep.tz, refDate);
  const arrOffset = getUtcOffsetHours(arr.tz, refDate);

  if (depOffset === null || arrOffset === null) {
    return {
      hasDifference: false,
      hourDifference: 0,
      headline: 'Timezone calculation failed',
      description: 'Could not compute timezone difference.',
      badge: 'UTC',
    };
  }

  const diff = arrOffset - depOffset;

  if (diff === 0) {
    const sign = arrOffset >= 0 ? `+${arrOffset}` : `${arrOffset}`;
    return {
      hasDifference: false,
      hourDifference: 0,
      headline: 'No timezone change',
      description: `${dep.city} and ${arr.city} are in the same timezone`,
      badge: `UTC${sign}`,
    };
  }

  const absDiff = Math.abs(diff);
  const isAhead = diff > 0;
  const unit = absDiff === 1 ? 'hr' : 'hrs';
  const relation = isAhead ? 'ahead' : 'behind';

  return {
    hasDifference: true,
    hourDifference: diff,
    headline: `${absDiff} ${unit} ${relation}`,
    description: `${arr.city} is ${absDiff} ${unit} ${relation} of ${dep.city}`,
    badge: `${isAhead ? '+' : '-'}${absDiff} ${unit}`,
  };
}
