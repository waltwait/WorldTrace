#!/usr/bin/env node
// Writes src/flights/countries.ts: every ISO country code with its name in
// Traditional Chinese. The flight API gives a code and the Android JS engine has
// no Intl.DisplayNames, so the names are made here, once, by Node's own ICU.
import { writeFileSync } from 'node:fs';

const names = new Intl.DisplayNames(['zh-Hant'], { type: 'region', style: 'short', fallback: 'none' });
const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';

const rows = [];
for (const a of letters) {
  for (const b of letters) {
    const code = a + b;
    const name = names.of(code);
    if (name && code !== 'ZZ') rows.push(`  ${code}: '${name}',`);
  }
}

writeFileSync(
  new URL('../src/flights/countries.ts', import.meta.url),
  `/**
 * Countries, from the ISO code the flight API gives. The names are generated by
 * tools/make-countries.mjs; a flag is just the code's two letters, moved up into
 * the regional indicator symbols.
 */

const NAMES: Record<string, string> = {
${rows.join('\n')}
};

export function countryName(code: string): string {
  return NAMES[code.toUpperCase()] ?? code;
}

const FIRST_INDICATOR = 0x1f1e6;

export function flagEmoji(code: string | null | undefined): string {
  const letters = (code ?? '').toUpperCase();
  if (!/^[A-Z]{2}$/.test(letters)) return '';
  return String.fromCodePoint(
    ...[...letters].map((letter) => FIRST_INDICATOR + letter.charCodeAt(0) - 65),
  );
}
`,
);
